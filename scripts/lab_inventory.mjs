#!/usr/bin/env node
// Regenerate static/js/lab/pages/<page>.js after changing the packs or surface modules.
// --check reports stale indexes without writing them.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { improvementsOf } from "../static/js/lab/kit.js";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PACKS_DIR = join(ROOT, "static/js/lab/packs");
const PAGES_DIR = join(ROOT, "static/js/lab/pages");
const SURFACES_DIR = join(ROOT, "static/js/lab/surfaces");
// The other Workbench surface builders have no surviving packs after the Lab prune.
const WORKBENCH_BUILDER_FILES = [
  "workbench-analysis.js",
  "workbench-build.js",
  "workbench-checks.js",
  "workbench-shell.js",
];
// Every page gets an index, even with no packs of its own, so its entry module can always import one.
export const PAGES = [
  "index",
  "shield",
  "dispatch",
  "autopilot",
  "claims",
  "reviews",
  "find",
  "play",
  "counter",
  "workbench",
];

export function packFiles() {
  if (!existsSync(PACKS_DIR)) return [];
  const out = [];
  for (const page of readdirSync(PACKS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()) {
    for (const file of readdirSync(join(PACKS_DIR, page))
      .filter((name) => name.endsWith(".js"))
      .sort())
      out.push({ page, file, path: join(PACKS_DIR, page, file) });
  }
  return out;
}

export async function loadJsPacks() {
  const packs = [];
  for (const entry of packFiles())
    packs.push({ ...entry, pack: (await import(pathToFileURL(entry.path).href)).default });
  return packs;
}

// The ctx-builder modules of a page: static/js/lab/surfaces/<page>.js and <page>-<area>.js.
export function surfaceFiles(page) {
  if (!existsSync(SURFACES_DIR)) return [];
  return readdirSync(SURFACES_DIR)
    .filter((name) => name === `${page}.js` || (name.startsWith(`${page}-`) && name.endsWith(".js")))
    .sort();
}

function pageIndex(page, files, surfaces) {
  const lines = [
    "// Generated by scripts/lab_inventory.mjs from static/js/lab/packs and static/js/lab/surfaces. Do not edit: run the",
    `// script again instead. The Lab packs the ${page} page loads (its own, then the page-wide "chrome" packs) and the`,
    "// ctx builders of its surfaces, which page code reaches as LAB.builders.",
    'import { createLab } from "../host.js";',
  ];
  surfaces.forEach((file, index) => lines.push(`import * as s${index} from "../surfaces/${file}";`));
  // Keep the chrome and packs with keyboard shortcuts ready before any tools are opened.
  const deferred =
    page === "workbench"
      ? files.filter(
          ({ pack, page: owner }) =>
            owner === page && !pack.features.some((feature) => feature.kind === "command" && feature.keys),
        )
      : [];
  const eager = files.filter((entry) => !deferred.includes(entry));
  eager.forEach((entry, index) => lines.push(`import p${index} from "../packs/${entry.page}/${entry.file}";`));
  lines.push("", `export const PACKS = [${eager.map((_, index) => `p${index}`).join(", ")}];`);
  const builders = `{ ${surfaces.map((_, index) => `...s${index}`).join(", ")} }`;
  if (deferred.length) {
    const counts = new Map();
    for (const { pack } of deferred) {
      counts.set(pack.surface, (counts.get(pack.surface) || 0) + improvementsOf(pack).length);
    }
    lines.push(
      `export const LAB = createLab(PACKS, ${builders}, {`,
      `  counts: ${JSON.stringify(Object.fromEntries(counts))},`,
      "  load: async () => (await Promise.all([",
      ...deferred.map(({ page: owner, file }) => `    import("../packs/${owner}/${file}"),`),
      "  ])).map((module) => module.default),",
      "});",
    );
  } else lines.push(`export const LAB = createLab(PACKS, ${builders});`);
  lines.push("");
  return lines.join("\n");
}

// Every generated file as a Map of repo-relative path -> content.
export async function generate() {
  const files = new Map();
  const loaded = await loadJsPacks();
  const chrome = loaded.filter((entry) => entry.page === "chrome");
  for (const page of PAGES) {
    const surfaces = surfaceFiles(page);
    const names = new Map();
    for (const file of surfaces) {
      for (const name of Object.keys(await import(pathToFileURL(join(SURFACES_DIR, file)).href))) {
        if (names.has(name))
          throw new Error(`static/js/lab/surfaces: ${file} and ${names.get(name)} both export ${name}`);
        names.set(name, file);
      }
    }
    files.set(
      `static/js/lab/pages/${page}.js`,
      pageIndex(
        page,
        [...loaded.filter((entry) => entry.page === page), ...chrome],
        page === "workbench" ? surfaces.filter((file) => WORKBENCH_BUILDER_FILES.includes(file)) : surfaces,
      ),
    );
  }

  return files;
}

// Paths of generated files on disk that differ from `files`, are missing, or should no longer exist.
export function staleFiles(files) {
  const stale = [];
  for (const [path, content] of files) {
    const full = join(ROOT, path);
    if (!existsSync(full) || readFileSync(full, "utf8") !== content) stale.push(path);
  }
  if (existsSync(PAGES_DIR)) {
    for (const name of readdirSync(PAGES_DIR)) {
      const path = relative(ROOT, join(PAGES_DIR, name)).replaceAll("\\", "/");
      if (!files.has(path)) stale.push(path);
    }
  }
  return stale;
}

async function main() {
  const check = process.argv.includes("--check");
  const files = await generate();
  const stale = staleFiles(files);
  if (check) {
    if (stale.length) {
      console.error(`Out of date: ${stale.join(", ")}\nRun: node scripts/lab_inventory.mjs`);
      process.exit(1);
    }
    console.log("Lab page indexes are up to date.");
    return;
  }
  for (const path of stale) {
    const full = join(ROOT, path);
    if (files.has(path)) {
      mkdirSync(dirname(full), { recursive: true });
      writeFileSync(full, files.get(path));
    } else rmSync(full);
  }
  console.log(`Lab page indexes: ${stale.length} file${stale.length === 1 ? "" : "s"} updated.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();

def mulberry_ctypes(seed):
    """The published C mulberry32 transcribed with ctypes.c_uint32, whose arithmetic wraps like C's uint32_t."""
    u32 = ctypes.c_uint32
    state = u32(seed)
    while True:
        state = u32(state.value + 0x6D2B79F5)
        t = state.value
        t = u32((t ^ (t >> 15)) * (t | 1)).value
        t ^= u32(t + u32((t ^ (t >> 7)) * (t | 61)).value).value
        yield u32(t ^ (t >> 14)).value / 4294967296


class RandomnessTests(unittest.TestCase):
    def test_mulberry32_is_the_published_algorithm(self):
        for seed in (0, 1, 42, -1, -123456, 2 ** 31, 2 ** 32 - 1, 2 ** 32, 2 ** 53 - 1, -(2 ** 53 - 1)):
            following, reference = mathx.mulberry32(seed), mulberry_ctypes(seed)
            for draw in range(500):
                value = following()
                self.assertEqual(value, next(reference), "mulberry32(%r) draw %d" % (seed, draw))
                self.assertTrue(0 <= value < 1)
        self.assertEqual(mathx.mulberry32(2 ** 32 + 5)(), mathx.mulberry32(5)())
        self.assertEqual(mathx.mulberry32(5.0)(), mathx.mulberry32(5)(), "an integral float is an integer seed")

    def test_shuffled(self):
        items = tuple("item %d" % i for i in range(50))
        once, twice = mathx.shuffled(items, 99), mathx.shuffled(items, 99)
        self.assertIsInstance(once, list)
        self.assertEqual(once, twice)
        self.assertEqual(sorted(once), sorted(items))
        self.assertNotEqual(once, list(items))
        self.assertNotEqual(mathx.shuffled(items, 100), once)
        source = list(items)
        mathx.shuffled(source, 1)
        self.assertEqual(source, list(items), "the input is not changed")
        self.assertEqual(mathx.shuffled([], 1), [])
        counts = [[0] * 4 for _ in range(4)]
        for seed in range(4000):
            for place, item in enumerate(mathx.shuffled([0, 1, 2, 3], seed)):
                counts[item][place] += 1
        for row in counts:
            for count in row:
                self.assertTrue(850 < count < 1150, counts)
        self.assertIsNone(mathx.shuffled("abc", 1))

    def test_sample_indexes(self):
        for count, size in ((10, 3), (100, 100), (1000, 1), (2 ** 32, 20), (7, 0), (500, 250)):
            for seed in (0, 5, -9):
                chosen = mathx.sample_indexes(count, size, seed)
                self.assertEqual(len(chosen), size)
                self.assertEqual(chosen, sorted(set(chosen)))
                self.assertTrue(all(isinstance(index, int) and 0 <= index < count for index in chosen))
                self.assertEqual(mathx.sample_indexes(count, size, seed), chosen)
        self.assertEqual(mathx.sample_indexes(5, 5, 3), [0, 1, 2, 3, 4])
        self.assertIsNone(mathx.sample_indexes(5, 6, 1))
        self.assertIsNone(mathx.sample_indexes(2 ** 32 + 1, 1, 1))



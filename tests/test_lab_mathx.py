class StandardLibraryTests(Close, unittest.TestCase):
    def test_error_function_and_normal_distribution(self):
        normal = statistics.NormalDist()
        for i in range(-400, 401):
            x = i / 64
            self.assertNear(mathx.erf(x), math.erf(x), 1e-15, "erf(%r)" % x)
            if x < 5:
                self.assertNear(mathx.erfc(x), math.erfc(x), 5e-15, "erfc(%r)" % x)
            # NormalDist.cdf is 1 + erf(...) and loses the left tail, so the comparison uses erfc instead
            self.assertNear(mathx.normal_cdf(x), 0.5 * math.erfc(-x / math.sqrt(2)), 1e-14, "normal_cdf(%r)" % x)
            self.assertNear(mathx.normal_pdf(x), normal.pdf(x), 1e-14, "normal_pdf(%r)" % x)
            self.assertEqual(mathx.normal_cdf(-x), mathx.normal_sf(x))
        for p in (1e-300, 1e-12, 0.001, 0.025, 0.2, 0.5, 0.8, 0.975, 0.999):
            self.assertNear(mathx.normal_quantile(p), normal.inv_cdf(p), 1e-15, "normal_quantile(%r)" % p)
        self.assertNear(mathx.normal_quantile(0.975), 1.959963984540054, 1e-15, "the published 97.5% point")

    def test_log_gamma_and_binomial_coefficients(self):
        # math.lgamma differs between builds by a few units in the last place, and near the zeros at 1 and 2 only
        # absolutely, so the comparison is relative to max(1, |ln gamma|)
        for x in (1e-8, 0.1, 0.5, 0.75, 1.25, 3.0, 4.5, 9.99, 10.01, 57.3, 1000.5, 1e7):
            expected = math.lgamma(x)
            self.assertLessEqual(abs(mathx.log_gamma(x) - expected), 5e-15 * max(1.0, abs(expected)), "log_gamma(%r)" % x)
        self.assertEqual(mathx.log_gamma(1), 0.0)
        self.assertEqual(mathx.log_gamma(2), 0.0)
        for n in range(0, 200):
            exact = Decimal(math.factorial(n)).ln() if n > 1 else Decimal(0)
            self.assertNear(mathx.log_factorial(n), float(exact), 2e-15, "log_factorial(%d)" % n)
        for n in range(0, 90):
            for k in range(0, n + 1):
                self.assertEqual(mathx.choose(n, k), float(math.comb(n, k)), "choose(%d, %d)" % (n, k))
                exact = math.comb(n, k)
                self.assertNear(mathx.log_choose(n, k), float(Decimal(exact).ln()) if exact > 1 else 0.0, 2e-15, "log_choose(%d, %d)" % (n, k))
        self.assertIsNone(mathx.choose(1030, 515))
        self.assertEqual(mathx.choose(1029, 514), float(math.comb(1029, 514)))

    def test_descriptive_statistics(self):
        following = mathx.mulberry32(2024)
        for size in (1, 2, 3, 10, 101):
            data = [round(following() * 1000 - 300, 3) for _ in range(size)]
            self.assertNear(mathx.sum(data), math.fsum(data), 1e-15, "sum")
            self.assertNear(mathx.mean(data), statistics.fmean(data), 1e-15, "mean")
            self.assertNear(mathx.median(data), statistics.median(data), 1e-15, "median")
            self.assertEqual(mathx.min_of(data), min(data))
            self.assertEqual(mathx.max_of(data), max(data))
            self.assertNear(mathx.variance(data, False), statistics.pvariance(data), 1e-13, "pvariance")
            self.assertNear(mathx.stdev(data, False), statistics.pstdev(data), 1e-13, "pstdev")
            if size >= 2:
                self.assertNear(mathx.variance(data), statistics.variance(data), 1e-13, "variance")
                self.assertNear(mathx.stdev(data), statistics.stdev(data), 1e-13, "stdev")
                # statistics.quantiles with method="inclusive" is type 7
                for q, cut in zip((0.25, 0.5, 0.75), statistics.quantiles(data, n=4, method="inclusive")):
                    self.assertNear(mathx.quantile(data, q), cut, 1e-13, "quantile %r" % q)
        self.assertEqual(mathx.sum([0.1, 0.2, 0.3]), 0.6)
        self.assertEqual(mathx.quantile([1, 2, 3, 4], 0.25), 1.75)
        data = [3, 1, 2]
        mathx.median(data)
        self.assertEqual(data, [3, 1, 2], "the input is not sorted in place")


class ClosedFormTests(Close, unittest.TestCase):
    def test_student_t_with_one_and_two_degrees_of_freedom(self):
        for t in (-1e6, -300.0, -3.0, -0.25, 0.25, 3.0, 300.0, 1e6):
            cauchy_tail = math.atan(1 / abs(t)) / math.pi
            self.assertNear(mathx.student_t_cdf(t, 1), cauchy_tail if t < 0 else 1 - cauchy_tail, 5e-15, "cdf(%r, 1)" % t)
            s = math.sqrt(2 + t * t)
            tail = 1 / (s * (s + abs(t)))
            self.assertNear(mathx.student_t_sf(-t, 2), tail if t < 0 else 1 - tail, 5e-15, "sf(%r, 2)" % -t)
        self.assertNear(mathx.student_t_cdf(-1e200, 1), 1 / (math.pi * 1e200), 1e-13, "t * t overflows, the tail does not")
        self.assertEqual(mathx.student_t_cdf(0, 3), 0.5)

    def test_chi_square_and_poisson_identities(self):
        for k in range(1, 20):
            for x in (0.5, 3.0, 7.5, 20.0):
                term, total = 1.0, 1.0
                for j in range(1, k):
                    term *= x / j
                    total += term
                q = math.exp(-x) * total
                if 1e-6 < q < 0.999:
                    self.assertNear(mathx.chi_square_sf(2 * x, 2 * k), q, 1e-13, "chi_square_sf(%r, %r)" % (2 * x, 2 * k))
                    self.assertNear(mathx.poisson_cdf(k - 1, x), q, 1e-13, "poisson_cdf(%r, %r)" % (k - 1, x))
        for x in (1e-10, 0.3, 4.0, 50.0):
            self.assertNear(mathx.chi_square_cdf(x, 2), -math.expm1(-x / 2), 4e-15, "chi_square_cdf(%r, 2)" % x)
        self.assertEqual(mathx.incomplete_gamma_p(5e-324, 1), 1.0)
        self.assertEqual(mathx.incomplete_gamma_p(5e-324, 0.9), 1.0, "x^a e^-x / gamma(a) underflows, P does not")

    def test_quantiles_published_and_closed_form(self):
        self.assertNear(mathx.student_t_quantile(0.975, 10), 2.2281388519649385, 1e-11, "as tables print it")
        self.assertNear(mathx.student_t_quantile(0.975, 10), 2.2281388519862747, 3e-16, "the even-df closed form solved in Decimal")
        self.assertNear(mathx.chi_square_quantile(0.95, 1), 3.841458820694124, 1e-15, "chi-square 0.95, 1 df")
        self.assertNear(mathx.chi_square_quantile(0.95, 10), 18.307038053275146, 1e-15, "chi-square 0.95, 10 df")
        for p in (0.001, 0.2, 0.6, 0.975, 0.999999):
            self.assertNear(mathx.chi_square_quantile(p, 2), -2 * math.log1p(-p), 1e-15, "chi-square 2 df at %r" % p)
            closed = -1 / math.tan(math.pi * p) if p < 0.5 else 1 / math.tan(math.pi * (1 - p))
            self.assertNear(mathx.student_t_quantile(p, 1), closed, 1e-14, "t 1 df at %r" % p)
            self.assertNear(mathx.student_t_quantile(p, 2), (2 * p - 1) / math.sqrt(2 * p * (1 - p)), 1e-13, "t 2 df at %r" % p)
            self.assertNear(mathx.beta_quantile(p, 3.5, 1), p ** (1 / 3.5), 1e-15, "Beta(a, 1) at %r" % p)

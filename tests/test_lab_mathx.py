def snake(name: str) -> str:
    return re.sub(r"([A-Z])", lambda match: "_" + match.group(1).lower(), name)


class Close:
    """assertNear with the table's convention: tolerance 0 (or an expected 0) means exactly equal, and None and booleans
    must come back as themselves. Every other result must be a float, as mathx promises."""

    def assertNear(self, actual, expected, tolerance, label):
        if expected is None or isinstance(expected, bool):
            self.assertIs(actual, expected, label)
            return
        self.assertIsInstance(actual, float, "%s: got %r, expected %r" % (label, actual, expected))
        if tolerance == 0 or expected == 0:
            self.assertEqual(actual, expected, label)
            return
        error = abs(actual - expected) / abs(expected)
        self.assertLessEqual(error, tolerance, "%s: got %r, expected %r (relative error %.2e)" % (label, actual, expected, error))


